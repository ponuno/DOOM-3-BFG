	"GL_ARB_draw_elements_base_vertex "
	"GL_ARB_fragment_program "
	"GL_ARB_uniform_buffer_object";

static GLuint nextName = 1;

static GLuint NullGL_NewName() {
	return nextName++;
}

static void NullGL_GenNames( GLsizei n, GLuint * names ) {
	for ( GLsizei i = 0; i < n; i++ ) {
		names[i] = NullGL_NewName();
	}
}

static const char * NullGL_GetString( GLenum name ) {
	switch ( name ) {
		case GL_VENDOR:						return "doom3ds";
		case GL_RENDERER:					return "null GL (New 3DS bring-up)";
		case GL_VERSION:					return "2.1 null";
		case GL_SHADING_LANGUAGE_VERSION:	return "1.20";
		case GL_EXTENSIONS:					return NULLGL_EXTENSIONS;
	}
	return "";
}

static void NullGL_GetIntegerv( GLenum pname, GLint * params ) {
	switch ( pname ) {
		case GL_MAX_TEXTURE_SIZE:					params[0] = 1024; break;
		case GL_MAX_TEXTURE_COORDS_ARB:				params[0] = 8; break;
		case GL_MAX_TEXTURE_IMAGE_UNITS_ARB:		params[0] = 16; break;
		case GL_UNIFORM_BUFFER_OFFSET_ALIGNMENT:	params[0] = 16; break;
		case GL_MAX_TEXTURE_MAX_ANISOTROPY_EXT:		params[0] = 1; break;
		case GL_NUM_EXTENSIONS:						params[0] = 0; break;
		case GL_VIEWPORT:
		case GL_SCISSOR_BOX:
			params[0] = 0; params[1] = 0; params[2] = 400; params[3] = 240; break;
		default:									params[0] = 0; break;
	}
}

static void NullGL_ReadPixels( GLsizei width, GLsizei height, GLenum format, GLenum type, GLvoid * pixels ) {
	int bpp = 4;
	if ( format == GL_RGB ) {
		bpp = 3;
	} else if ( format == GL_DEPTH_COMPONENT || format == GL_STENCIL_INDEX ) {
		bpp = ( type == GL_FLOAT || type == GL_UNSIGNED_INT ) ? 4 : 1;
	}
	if ( pixels != NULL ) {
		memset( pixels, 0, (size_t)width * height * bpp );
	}
}

/*
================================================================================================

	Buffer objects in RAM

================================================================================================
*/

struct nullBuffer_t {
	GLuint		name;
	byte *		data;
	GLsizeiptr	size;
	bool		linear;		// allocated from the 3DS linear heap
};

/*
	Buffer storage. On 3DS the vertex cache buffers go to the linear heap when they
	fit: that memory is otherwise unused by the null driver, and it is where citro3d
	needs vertex/index data anyway. Larger ones fall back to the engine heap.
*/
static void NullGL_AllocStorage( nullBuffer_t * b, GLsizeiptr size ) {
	b->linear = false;
	b->data = NULL;
#if defined( ID_3DS )
	if ( linearSpaceFree() > (u32)size + NULLGL_LINEAR_RESERVE ) {
		b->data = (byte *)linearMemAlign( size, 128 );
		if ( b->data != NULL ) {
			b->linear = true;
			idLib::Printf( "null GL: buffer %u, %d KB in linear memory (%d KB left)\n",
				b->name, (int)( size / 1024 ), (int)( linearSpaceFree() / 1024 ) );
			return;
		}
	}
#endif
	b->data = (byte *)Mem_Alloc16( (int)size, TAG_RENDER );
	idLib::Printf( "null GL: buffer %u, %d KB in heap\n", b->name, (int)( size / 1024 ) );
}

static void NullGL_FreeStorage( nullBuffer_t * b ) {
	if ( b->data == NULL ) {
		return;
	}
#if defined( ID_3DS )
	if ( b->linear ) {
		linearFree( b->data );
		b->data = NULL;
		return;
	}
#endif
	Mem_Free16( b->data );
	b->data = NULL;
}

static idList< nullBuffer_t, TAG_RENDER >	buffers;
static GLuint boundArray = 0;
static GLuint boundElement = 0;
static GLuint boundUniform = 0;

static nullBuffer_t * NullGL_FindBuffer( GLuint name ) {
	for ( int i = 0; i < buffers.Num(); i++ ) {
		if ( buffers[i].name == name ) {
			return &buffers[i];
		}
	}
	return NULL;
}

static GLuint * NullGL_Binding( GLenum target ) {
	switch ( target ) {
		case GL_ARRAY_BUFFER:			return &boundArray;
		case GL_ELEMENT_ARRAY_BUFFER:	return &boundElement;
		case GL_UNIFORM_BUFFER:			return &boundUniform;
	}
	return NULL;
}

static nullBuffer_t * NullGL_Bound( GLenum target ) {
	GLuint * b = NullGL_Binding( target );
	return ( b != NULL && *b != 0 ) ? NullGL_FindBuffer( *b ) : NULL;
}

static void NullGL_GenBuffers( GLsizei n, GLuint * names ) {
	for ( GLsizei i = 0; i < n; i++ ) {
		nullBuffer_t b;
		b.name = NullGL_NewName();
		b.data = NULL;
		b.size = 0;
		b.linear = false;
		buffers.Append( b );
		names[i] = b.name;
	}
}

static void NullGL_DeleteBuffers( GLsizei n, const GLuint * names ) {
	for ( GLsizei i = 0; i < n; i++ ) {
		for ( int j = 0; j < buffers.Num(); j++ ) {
			if ( buffers[j].name == names[i] ) {
				NullGL_FreeStorage( &buffers[j] );
				buffers.RemoveIndexFast( j );
				break;
			}
		}
	}
}

static void NullGL_BindBuffer( GLenum target, GLuint name ) {
	GLuint * b = NullGL_Binding( target );
	if ( b != NULL ) {
		*b = name;
	}
}

/*
	Storage is allocated lazily, on the first write or map: a buffer that is
	only ever sized (the static vertex cache when its uploads are discarded)
	costs nothing.
*/
static bool NullGL_EnsureStorage( nullBuffer_t * b ) {
	if ( b->data == NULL && b->size > 0 ) {
		NullGL_AllocStorage( b, b->size );
	}
	return b->data != NULL;
}

static void NullGL_BufferData( GLenum target, GLsizeiptr size, const GLvoid * data ) {
	nullBuffer_t * b = NullGL_Bound( target );
	if ( b == NULL ) {
		return;
	}
	if ( b->size != size ) {
		NullGL_FreeStorage( b );
		b->size = size;
	}
	if ( data != NULL && NullGL_EnsureStorage( b ) ) {
		memcpy( b->data, data, size );
	}
}

static void NullGL_BufferSubData( GLenum target, GLintptr offset, GLsizeiptr size, const GLvoid * data ) {
	nullBuffer_t * b = NullGL_Bound( target );
	if ( b != NULL && offset + size <= b->size && NullGL_EnsureStorage( b ) ) {
		memcpy( b->data + offset, data, size );
	}
}

static void NullGL_GetBufferSubData( GLenum target, GLintptr offset, GLsizeiptr size, GLvoid * data ) {
	nullBuffer_t * b = NullGL_Bound( target );
	if ( b != NULL && b->data != NULL && offset + size <= b->size ) {
		memcpy( data, b->data + offset, size );
	} else if ( data != NULL ) {
		memset( data, 0, size );
	}
}

static GLvoid * NullGL_MapBuffer( GLenum target, GLintptr offset ) {
	nullBuffer_t * b = NullGL_Bound( target );
	if ( b == NULL || !NullGL_EnsureStorage( b ) ) {
		return NULL;
	}
	return b->data + offset;
}

static GLboolean NullGL_IsBuffer( GLuint name ) {
	return NullGL_FindBuffer( name ) != NULL ? GL_TRUE : GL_FALSE;
}

static void NullGL_GetBufferParameteriv( GLenum target, GLenum pname, GLint * params ) {
	nullBuffer_t * b = NullGL_Bound( target );
	params[0] = ( pname == GL_BUFFER_SIZE && b != NULL ) ? (GLint)b->size : 0;
}

