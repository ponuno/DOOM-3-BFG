/*
================================================================================================

	Null OpenGL driver for the New 3DS bring-up build.

	GENERATED by gen_gl_null.py from gl_null.cpp.in -- edit those, not gl_null.cpp.

	Nothing reaches a GPU. Buffer objects are emulated in RAM because the
	vertex cache writes through mapped pointers; everything else is a no-op
	that returns plausible values. The citro3d backend replaces this as it
	grows.

================================================================================================
*/

